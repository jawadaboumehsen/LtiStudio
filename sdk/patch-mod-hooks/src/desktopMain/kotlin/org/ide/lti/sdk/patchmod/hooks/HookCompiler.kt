package org.ide.lti.sdk.patchmod.hooks

import com.android.tools.r8.CompilationMode
import com.android.tools.r8.D8
import com.android.tools.r8.D8Command
import com.android.tools.r8.DirectoryClassFileProvider
import com.android.tools.r8.JdkClassFileProvider
import com.android.tools.r8.OutputMode
import com.android.tools.smali.baksmali.Baksmali
import com.android.tools.smali.baksmali.BaksmaliOptions
import com.android.tools.smali.dexlib2.DexFileFactory
import com.android.tools.smali.dexlib2.Opcodes
import com.googlecode.d2j.dex.Dex2jar
import kotlinx.serialization.Serializable
import java.io.File
import java.io.StringWriter
import java.security.MessageDigest
import java.util.zip.ZipEntry
import java.util.zip.ZipFile
import java.util.zip.ZipOutputStream
import javax.tools.ToolProvider

/**
 * Compiles a mod's hook classes from Java to the smali files it adds to a component (`addFile`), so hooks are written
 * and reviewed as Java, not hand-written smali. The classpath is the firmware's own code: each [firmware] jar or APK
 * is turned into a signatures-only jar (dex2jar), so a hook calls hidden framework APIs exactly as that firmware has
 * them. Then javac, d8 and baksmali.
 *
 * Java, not Kotlin: a Kotlin class needs the Kotlin runtime, and `kotlin.*` classes added to framework.jar would
 * shadow every app's own Kotlin.
 */
object HookCompiler {

    /** One source root (`hooks/…/io/lti/Foo.java`) and the folder its smali goes to (`files/…/smali_classes6`). */
    data class Root(val sources: File, val out: File)

    /** The first line of every smali file the compiler writes; such files are replaced on the next compile. */
    const val GENERATED_HEADER: String = "# Generated by HookCompiler from Java: edit the source, not this file."

    /**
     * Compiles all [roots] together (a hook may use another root's classes) and writes each root's classes as smali
     * under its [Root.out], replacing the smali files it generated before. [work] keeps the converted firmware
     * jars between runs. Returns the problems found; nothing is written when there are any.
     */
    fun compile(roots: List<Root>, firmware: List<File>, work: File, minApi: Int = DEFAULT_MIN_API): List<String> {
        val classpath = firmware.map { stubJar(it, work.resolve("classpath")) }
        // d8 refuses a class defined in two classpath entries, and a plain jar (android.jar) repeats the firmware's.
        val dexClasspath = firmware.zip(classpath).filter { (from, stub) -> from != stub }.map { it.second }
        val classes = work.resolve("classes").also { it.deleteRecursively() }
        val sources = roots.flatMap { root -> javaFiles(root.sources) }
        val problems = if (sources.isEmpty()) {
            listOf("No Java sources in ${roots.map { it.sources }}")
        } else {
            javac(sources, classpath, classes)
        }
        if (problems.isNotEmpty()) return problems
        val smali = roots.associateWith { root ->
            val dex = work.resolve("dex/${root.out.path.hashCode().toUInt()}").also { it.deleteRecursively() }
            d8(classFilesOf(root, classes), classes, dexClasspath, dex, minApi)
            baksmali(dex, work.resolve("smali/${dex.name}").also { it.deleteRecursively() }, minApi)
        }
        val refused = smali.values.flatMap { dir -> check(dir) }
        if (refused.isEmpty()) smali.forEach { (root, dir) -> publish(dir, root.out) }
        return refused
    }

    private fun javaFiles(dir: File) = dir.walkTopDown().filter { it.isFile && it.extension == "java" }.toList()

    /**
     * A signatures-only jar of [file]'s dex, cached by the file's sha256. A plain jar of classes (the SDK's
     * `android.jar`, for the libraries a firmware keeps outside its framework, like `org.xmlpull`) is used as it is.
     */
    private fun stubJar(file: File, cache: File): File {
        if (file.extension == "jar" && ZipFile(file).use { it.getEntry("classes.dex") == null }) return file
        val jar = cache.resolve("${file.name}-${sha256(file).take(HASH_PREFIX)}-$STUB_FORMAT.jar")
        if (!jar.isFile) {
            cache.mkdirs()
            val converted = File(jar.path + ".converted").also { it.delete() }
            val partial = File(jar.path + ".partial").also { it.delete() }
            Dex2jar.from(file).noCode(true).skipDebug(true).skipExceptions(true).to(converted.toPath())
            withoutDesugarHelpers(converted, partial)
            converted.delete()
            check(partial.renameTo(jar)) { "Cannot write ${jar.path}" }
        }
        return jar
    }

    /** An R8-built app carries R8's helper classes (`RecordTag`, …), which clash with the JDK's on d8's classpath. */
    private fun withoutDesugarHelpers(from: File, to: File) {
        ZipFile(from).use { zip ->
            ZipOutputStream(to.outputStream().buffered()).use { out ->
                zip.entries().asSequence().filterNot { it.name.startsWith("com/android/tools/r8/") }.forEach { entry ->
                    out.putNextEntry(ZipEntry(entry.name))
                    zip.getInputStream(entry).use { it.copyTo(out) }
                    out.closeEntry()
                }
            }
        }
    }

    private fun javac(sources: List<File>, classpath: List<File>, out: File): List<String> {
        val compiler = ToolProvider.getSystemJavaCompiler()
            ?: return listOf("javac is not available: run with a JDK, not a JRE")
        out.mkdirs()
        val errors = StringWriter()
        val options = listOf(
            "-d", out.path,
            "-classpath", classpath.joinToString(File.pathSeparator),
            "--release", JAVA_RELEASE,
            "-proc:none",
            "-g:source,lines",
            "-encoding", "UTF-8",
            "-nowarn",
        )
        val files = compiler.getStandardFileManager(null, null, Charsets.UTF_8).getJavaFileObjectsFromFiles(sources)
        val ok = compiler.getTask(errors, null, null, options, null, files).call()
        val classpathNames = classpath.joinToString { it.name }
        return if (ok) emptyList() else listOf("javac failed (classpath: $classpathNames):\n$errors")
    }

    /** [root]'s classes among [classes]: each of its sources' top-level class and that class's nested ones. */
    private fun classFilesOf(root: Root, classes: File): List<File> {
        val names = javaFiles(root.sources).map {
            it.relativeTo(root.sources).path.replace('\\', '/').removeSuffix(".java")
        }
        return classes.walkTopDown().filter { it.isFile && it.extension == "class" }.filter { file ->
            val name = file.relativeTo(classes).path.replace('\\', '/').removeSuffix(".class")
            names.any { name == it || name.startsWith("$it$") }
        }.toList()
    }

    private fun d8(program: List<File>, classes: File, classpath: List<File>, out: File, minApi: Int) {
        out.mkdirs()
        val command = D8Command.builder()
            .addProgramFiles(program.map { it.toPath() })
            .addClasspathFiles(classpath.map { it.toPath() })
            // Another root's classes are referenced, not compiled in again (program classes take precedence).
            .addClasspathResourceProvider(DirectoryClassFileProvider.fromDirectory(classes.toPath()))
            .addLibraryResourceProvider(JdkClassFileProvider.fromSystemJdk())
            .setMinApiLevel(minApi)
            .setMode(CompilationMode.RELEASE)
            .setOutput(out.toPath(), OutputMode.DexIndexed)
        D8.run(command.build())
    }

    private fun baksmali(dex: File, out: File, minApi: Int): File {
        dex.listFiles { f -> f.extension == "dex" }.orEmpty().sorted().forEach { file ->
            val dexFile = DexFileFactory.loadDexFile(file, Opcodes.forApi(minApi))
            check(Baksmali.disassembleDexFile(dexFile, out, 1, BaksmaliOptions())) { "baksmali failed on $file" }
        }
        return out
    }

    /** Classes in platform packages would shadow the firmware's own; Kotlin's runtime is not in the firmware. */
    private fun check(smali: File): List<String> = smali.walkTopDown().filter { it.extension == "smali" }.flatMap { f ->
        val rel = f.relativeTo(smali).path.replace('\\', '/')
        listOfNotNull(
            "$rel is in a platform package".takeIf { PLATFORM_PACKAGES.any { rel.startsWith(it) } },
            "$rel uses the Kotlin runtime".takeIf { "Lkotlin/" in f.readText() },
        )
    }.toList()

    /** Replaces the generated smali under [out] with [smali]'s files, each starting with [GENERATED_HEADER]. */
    private fun publish(smali: File, out: File) {
        out.walkTopDown().filter { it.isFile && it.extension == "smali" }
            .filter { it.useLines { lines -> lines.firstOrNull() == GENERATED_HEADER } }
            .forEach { it.delete() }
        smali.walkTopDown().filter { it.isFile && it.extension == "smali" }.forEach { f ->
            val target = out.resolve(f.relativeTo(smali).path)
            target.parentFile.mkdirs()
            target.writeText("$GENERATED_HEADER\n" + f.readText().replace("\r\n", "\n"))
        }
    }

    private fun sha256(file: File): String = MessageDigest.getInstance("SHA-256").let { md ->
        file.inputStream().use { input ->
            val buffer = ByteArray(BUFFER_BYTES)
            while (true) {
                val read = input.read(buffer)
                if (read < 0) break
                md.update(buffer, 0, read)
            }
        }
        md.digest().joinToString("") { "%02x".format(it) }
    }

    /** Android 14: the oldest runtime LtiRom's firmwares have. */
    const val DEFAULT_MIN_API: Int = 34
    private const val JAVA_RELEASE = "17"
    private const val HASH_PREFIX = 16

    /** Bump when what a stub jar holds changes, so older cached ones are not reused. */
    private const val STUB_FORMAT = "v2"
    private const val BUFFER_BYTES = 1 shl 16
    private val PLATFORM_PACKAGES = listOf("android/", "java/", "javax/", "kotlin/", "dalvik/", "com/android/")
}

/**
 * `payload.json`: the target firmware's jars and APKs the hooks are compiled against (`framework.jar`,
 * `services.jar`, …, relative to the project or absolute), and the oldest Android API they run on.
 */
@Serializable
data class PayloadConfig(
    val minRuntimeApi: Int = HookCompiler.DEFAULT_MIN_API,
    val firmware: List<String> = emptyList(),
)
