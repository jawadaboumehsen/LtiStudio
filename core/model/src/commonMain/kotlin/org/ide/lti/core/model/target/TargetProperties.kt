package org.ide.lti.core.model.target

/**
 * Mutable/configurable domain model representing all properties of a target's `ltikt.properties`.
 *
 * Provides bidirectional conversion:
 * - Parsing from standard Java/Kotlin properties file strings.
 * - Serializing to canonical, comment-grouped `ltikt.properties` text.
 * - Initializing from [TargetDevice] specifications.
 */
data class TargetProperties(
    // 1. Target Identity
    val targetId: String = "PQ84P01",
    val targetName: String = "REDMAGIC Astra Gaming Tablet",
    val targetCodename: String = "PQ84P01",
    val deviceCodename: String = "PQ84P01",
    val deviceProductName: String = "PQ84P01-EEA",
    val targetAssertModel: String = "PQ84P01",
    val deviceFastbootProduct: String = "sun",
    val targetFirmware: String = "PQ84P01:15/AQ3A.240812.002/20260311.222527",

    // 2. Versioning
    val versionMajor: Int = 1,
    val versionMinor: Int = 0,
    val versionPatch: Int = 0,
    val romVersion: String = "1.0.0",
    val targetFirmwareProduct: String = "",
    val targetFirmwareDevice: String = "",
    val targetFirmwareIncremental: String = "",
    val targetFirmwareSecurityPatch: String = "",
    val targetBootFirmwareProduct: String = "",
    val targetBootFirmwareDevice: String = "",
    val targetBootFirmwareIncremental: String = "",
    val targetBootFirmwareSecurityPatch: String = "",
    // Left blank by default (not "0") - LtiRomKt/app/.../env/ConfigLoader.kt only treats this key
    // as "provided" when non-blank, and auto-derives a real current epoch-seconds timestamp when
    // it's absent/blank. A hardcoded placeholder here would suppress that and stamp every build "0".
    val romBuildTimestamp: String = "",
    val romIsOfficial: Boolean = false,

    // 3. Firmware Acquisition
    val targetFirmwareSource: String = "ota",
    val targetFirmwareSourceOtaUrl: String = "",
    val targetFirmwareSourceOtaSha256: String = "",
    val targetFirmwareSourceOtaSha256Unavailable: Boolean = true,
    val targetFirmwareSourceZipImageUrl: String = "",
    val targetFirmwareSourceZipImageSha256: String = "",
    val targetFirmwareSourceZipImageSha256Unavailable: Boolean = false,

    // 4. Filesystem & Partitions
    val targetFsType: String = "erofs",
    val targetHasSystemExt: Boolean = true,
    val targetFlashablePartitions: String = "system vendor product system_ext odm vendor_dlkm system_dlkm",
    val targetFlashableBootPartitions: String = "boot init_boot vendor_boot dtbo",
    val targetFlashableBootSlots: String = "a b",
    val targetFirmwareSourceDir: String = "out/fw/PQ84P01/zip_image_extracted",
    val targetRecoverySystemMountPoint: String = "/system_root",
    val targetRecoveryDynamicPartitionMetadataPolicy: String = "device-first-with-package-fallback",

    // 5. Super Geometry & Partition Sizes
    val superPartitionSize: Long = 17179869184L,
    val superMetadataSlots: Int = 3,
    val superVirtualAb: Boolean = true,
    val targetDisableAvbSigning: Boolean = false,
    val superGroupName: String = "qti_dynamic_partitions_a",
    val superGroupSize: Long = 17175674880L,
    val bootPartitionSize: Long = 100663296L,
    val vendorBootPartitionSize: Long = 100663296L,
    val initBootPartitionSize: Long = 8388608L,
    val dtboPartitionSize: Long = 25165824L,
    val avbSigningKey: String = "security/avb/lti_rsa4096.pem",
    val bootDevicePath: String = "/dev/block/bootdevice/by-name",

    // 6. Build Policy & Networking
    val targetBuildType: String = "user",
    val otaBaseUrl: String = "https://example.com/updates",
) {

    /**
     * Serializes this configuration to standard canonical `ltikt.properties` format.
     */
    fun toPropertiesString(): String {
        return buildString {
            appendLine("# LtiRomKt build configuration — generated by LtiRom Studio")
            appendLine("# Target Identity")
            appendLine("TARGET_ID=$targetId")
            appendLine("TARGET_NAME=$targetName")
            appendLine("TARGET_CODENAME=$targetCodename")
            appendLine("DEVICE_CODENAME=$deviceCodename")
            appendLine("DEVICE_PRODUCT_NAME=$deviceProductName")
            appendLine("TARGET_ASSERT_MODEL=$targetAssertModel")
            appendLine("DEVICE_FASTBOOT_PRODUCT=$deviceFastbootProduct")
            appendLine("TARGET_FIRMWARE=$targetFirmware")
            appendLine("TARGET_FIRMWARE_PRODUCT=$targetFirmwareProduct")
            appendLine("TARGET_FIRMWARE_DEVICE=$targetFirmwareDevice")
            appendLine("TARGET_FIRMWARE_INCREMENTAL=$targetFirmwareIncremental")
            appendLine("TARGET_FIRMWARE_SECURITY_PATCH=$targetFirmwareSecurityPatch")
            appendLine("TARGET_BOOT_FIRMWARE_PRODUCT=$targetBootFirmwareProduct")
            appendLine("TARGET_BOOT_FIRMWARE_DEVICE=$targetBootFirmwareDevice")
            appendLine("TARGET_BOOT_FIRMWARE_INCREMENTAL=$targetBootFirmwareIncremental")
            appendLine("TARGET_BOOT_FIRMWARE_SECURITY_PATCH=$targetBootFirmwareSecurityPatch")
            appendLine()
            appendLine("# Versioning")
            appendLine("VERSION_MAJOR=$versionMajor")
            appendLine("VERSION_MINOR=$versionMinor")
            appendLine("VERSION_PATCH=$versionPatch")
            appendLine("ROM_VERSION=$romVersion")
            appendLine("ROM_IS_OFFICIAL=$romIsOfficial")
            appendLine("ROM_BUILD_TIMESTAMP=$romBuildTimestamp")
            appendLine()
            appendLine("# Firmware Acquisition")
            appendLine("TARGET_FIRMWARE_SOURCE=$targetFirmwareSource")
            appendLine("TARGET_FIRMWARE_SOURCE_OTA_URL=$targetFirmwareSourceOtaUrl")
            appendLine("TARGET_FIRMWARE_SOURCE_OTA_SHA256=$targetFirmwareSourceOtaSha256")
            appendLine("TARGET_FIRMWARE_SOURCE_OTA_SHA256_UNAVAILABLE=$targetFirmwareSourceOtaSha256Unavailable")
            appendLine("TARGET_FIRMWARE_SOURCE_ZIP_IMAGE_URL=$targetFirmwareSourceZipImageUrl")
            appendLine("TARGET_FIRMWARE_SOURCE_ZIP_IMAGE_SHA256=$targetFirmwareSourceZipImageSha256")
            appendLine("TARGET_FIRMWARE_SOURCE_ZIP_IMAGE_SHA256_UNAVAILABLE=$targetFirmwareSourceZipImageSha256Unavailable")
            appendLine()
            appendLine("# Filesystem & Partitions")
            appendLine("TARGET_FS_TYPE=$targetFsType")
            appendLine("TARGET_HAS_SYSTEM_EXT=$targetHasSystemExt")
            appendLine("TARGET_FLASHABLE_PARTITIONS=$targetFlashablePartitions")
            appendLine("TARGET_FLASHABLE_BOOT_PARTITIONS=$targetFlashableBootPartitions")
            appendLine("TARGET_FLASHABLE_BOOT_SLOTS=$targetFlashableBootSlots")
            appendLine("TARGET_FIRMWARE_SOURCE_DIR=$targetFirmwareSourceDir")
            appendLine("TARGET_RECOVERY_SYSTEM_MOUNT_POINT=$targetRecoverySystemMountPoint")
            appendLine("TARGET_RECOVERY_DYNAMIC_PARTITION_METADATA_POLICY=$targetRecoveryDynamicPartitionMetadataPolicy")
            appendLine()
            appendLine("# Super Geometry")
            appendLine("SUPER_PARTITION_SIZE=$superPartitionSize")
            appendLine("SUPER_METADATA_SLOTS=$superMetadataSlots")
            appendLine("SUPER_VIRTUAL_AB=$superVirtualAb")
            appendLine("TARGET_DISABLE_AVB_SIGNING=$targetDisableAvbSigning")
            appendLine("SUPER_GROUP_NAME=$superGroupName")
            appendLine("SUPER_GROUP_SIZE=$superGroupSize")
            appendLine("BOOT_PARTITION_SIZE=$bootPartitionSize")
            appendLine("VENDOR_BOOT_PARTITION_SIZE=$vendorBootPartitionSize")
            appendLine("INIT_BOOT_PARTITION_SIZE=$initBootPartitionSize")
            appendLine("DTBO_PARTITION_SIZE=$dtboPartitionSize")
            appendLine("AVB_SIGNING_KEY=$avbSigningKey")
            appendLine("BOOT_DEVICE_PATH=$bootDevicePath")
            appendLine()
            appendLine("# Build Policy")
            appendLine("TARGET_BUILD_TYPE=$targetBuildType")
            appendLine("OTA_BASE_URL=$otaBaseUrl")
        }
    }

    companion object {

        /**
         * Creates a [TargetProperties] populated from a canonical [TargetDevice] model.
         *
         * Boot firmware identity fields mirror target firmware identity because the source model does not track boot-image firmware identity separately.
         */
        fun fromTargetDevice(target: TargetDevice): TargetProperties {
            val regionSuffix = when (target.selectedRegion) {
                TargetRegion.GLOBAL -> "EEA"
                TargetRegion.CHINA -> "CN"
            }
            val sourceMode = when (target.acquisitionMode) {
                FirmwareAcquisitionMode.OTA -> "ota"
                FirmwareAcquisitionMode.ZIP_IMAGE -> "zip_image"
            }
            val otaUrl = target.selectedFirmware.otaUrl.orEmpty()
            val firmwareBuild = target.selectedFirmware.buildId.ifBlank {
                "${target.codename}:15/AQ3A.240812.002/20260311.222527"
            }
            val incremental = target.selectedFirmware.buildId.substringAfterLast('/')
            val deviceProductName = "${target.codename}-$regionSuffix"

            return TargetProperties(
                targetId = target.targetKey,
                targetName = target.name,
                targetCodename = target.codename,
                deviceCodename = target.codename,
                deviceProductName = deviceProductName,
                targetAssertModel = target.codename,
                deviceFastbootProduct = "sun",
                targetFirmware = firmwareBuild,
                targetFirmwareProduct = deviceProductName,
                targetFirmwareDevice = target.codename,
                targetFirmwareIncremental = incremental,
                targetFirmwareSecurityPatch = target.selectedFirmware.securityPatch,
                targetBootFirmwareProduct = deviceProductName,
                targetBootFirmwareDevice = target.codename,
                targetBootFirmwareIncremental = incremental,
                targetBootFirmwareSecurityPatch = target.selectedFirmware.securityPatch,
                versionMajor = 1,
                versionMinor = 0,
                versionPatch = 0,
                romVersion = "1.0.0",
                romBuildTimestamp = "",
                romIsOfficial = target.selectedFirmware.isOfficial,
                targetFirmwareSource = sourceMode,
                targetFirmwareSourceOtaUrl = otaUrl,
                targetFirmwareSourceOtaSha256 = "",
                targetFirmwareSourceOtaSha256Unavailable = true,
                targetFirmwareSourceZipImageUrl = "",
                targetFirmwareSourceZipImageSha256 = "",
                targetFirmwareSourceZipImageSha256Unavailable = false,
                targetFsType = target.filesystemType,
                // Must agree with targetFlashablePartitions - LtiRomKt derives "does this target
                // have a system_ext partition" from TARGET_FLASHABLE_PARTITIONS list membership
                // (ModulesContext.readOnly()), not from this flag, and (once ConfigLoader.kt's
                // consistency check lands) will reject a config where the two disagree.
                targetHasSystemExt = "system_ext" in target.dynamicPartitions,
                targetFlashablePartitions = target.dynamicPartitions.joinToString(" "),
                targetFlashableBootPartitions = target.bootPartitions.joinToString(" "),
                targetFlashableBootSlots = "a b",
                targetFirmwareSourceDir = "out/fw/${target.targetKey}/zip_image_extracted",
                targetRecoverySystemMountPoint = "/system_root",
                targetRecoveryDynamicPartitionMetadataPolicy = "device-first-with-package-fallback",
                superPartitionSize = target.superPartitionBytes,
                superMetadataSlots = 3,
                superVirtualAb = true,
                targetDisableAvbSigning = false,
                superGroupName = "qti_dynamic_partitions_a",
                superGroupSize = target.superGroupBytes,
                bootPartitionSize = target.bootPartitionBytes,
                vendorBootPartitionSize = target.vendorBootPartitionBytes,
                initBootPartitionSize = target.initBootPartitionBytes,
                dtboPartitionSize = target.dtboPartitionBytes,
                avbSigningKey = "security/avb/lti_rsa4096.pem",
                bootDevicePath = "/dev/block/bootdevice/by-name",
                targetBuildType = "user",
                otaBaseUrl = "https://example.com/updates",
            )
        }

        /**
         * Parses a key=value properties string into a [TargetProperties] instance,
         * falling back to default values for any missing keys.
         */
        fun parse(text: String, fallback: TargetProperties = TargetProperties()): TargetProperties {
            val map = mutableMapOf<String, String>()
            text.lineSequence().forEach { rawLine ->
                val line = rawLine.trim()
                if (line.isNotEmpty() && !line.startsWith("#") && !line.startsWith("!")) {
                    val eqIndex = line.indexOf('=')
                    if (eqIndex != -1) {
                        val key = line.substring(0, eqIndex).trim()
                        val value = line.substring(eqIndex + 1).trim()
                        map[key] = value
                    }
                }
            }

            return TargetProperties(
                targetId = map["TARGET_ID"] ?: fallback.targetId,
                targetName = map["TARGET_NAME"] ?: fallback.targetName,
                targetCodename = map["TARGET_CODENAME"] ?: fallback.targetCodename,
                deviceCodename = map["DEVICE_CODENAME"] ?: fallback.deviceCodename,
                deviceProductName = map["DEVICE_PRODUCT_NAME"] ?: fallback.deviceProductName,
                targetAssertModel = map["TARGET_ASSERT_MODEL"] ?: fallback.targetAssertModel,
                deviceFastbootProduct = map["DEVICE_FASTBOOT_PRODUCT"] ?: fallback.deviceFastbootProduct,
                targetFirmware = map["TARGET_FIRMWARE"] ?: fallback.targetFirmware,
                targetFirmwareProduct = map["TARGET_FIRMWARE_PRODUCT"] ?: fallback.targetFirmwareProduct,
                targetFirmwareDevice = map["TARGET_FIRMWARE_DEVICE"] ?: fallback.targetFirmwareDevice,
                targetFirmwareIncremental = map["TARGET_FIRMWARE_INCREMENTAL"] ?: fallback.targetFirmwareIncremental,
                targetFirmwareSecurityPatch = map["TARGET_FIRMWARE_SECURITY_PATCH"] ?: fallback.targetFirmwareSecurityPatch,
                targetBootFirmwareProduct = map["TARGET_BOOT_FIRMWARE_PRODUCT"] ?: fallback.targetBootFirmwareProduct,
                targetBootFirmwareDevice = map["TARGET_BOOT_FIRMWARE_DEVICE"] ?: fallback.targetBootFirmwareDevice,
                targetBootFirmwareIncremental = map["TARGET_BOOT_FIRMWARE_INCREMENTAL"] ?: fallback.targetBootFirmwareIncremental,
                targetBootFirmwareSecurityPatch = map["TARGET_BOOT_FIRMWARE_SECURITY_PATCH"] ?: fallback.targetBootFirmwareSecurityPatch,
                versionMajor = map["VERSION_MAJOR"]?.toIntOrNull() ?: fallback.versionMajor,
                versionMinor = map["VERSION_MINOR"]?.toIntOrNull() ?: fallback.versionMinor,
                versionPatch = map["VERSION_PATCH"]?.toIntOrNull() ?: fallback.versionPatch,
                romVersion = map["ROM_VERSION"] ?: fallback.romVersion,
                romBuildTimestamp = map["ROM_BUILD_TIMESTAMP"] ?: fallback.romBuildTimestamp,
                romIsOfficial = map["ROM_IS_OFFICIAL"]?.toBooleanStrictOrNull() ?: fallback.romIsOfficial,
                targetFirmwareSource = map["TARGET_FIRMWARE_SOURCE"] ?: fallback.targetFirmwareSource,
                targetFirmwareSourceOtaUrl = map["TARGET_FIRMWARE_SOURCE_OTA_URL"] ?: fallback.targetFirmwareSourceOtaUrl,
                targetFirmwareSourceOtaSha256 = map["TARGET_FIRMWARE_SOURCE_OTA_SHA256"] ?: fallback.targetFirmwareSourceOtaSha256,
                targetFirmwareSourceOtaSha256Unavailable = map["TARGET_FIRMWARE_SOURCE_OTA_SHA256_UNAVAILABLE"]?.toBooleanStrictOrNull()
                    ?: fallback.targetFirmwareSourceOtaSha256Unavailable,
                targetFirmwareSourceZipImageUrl = map["TARGET_FIRMWARE_SOURCE_ZIP_IMAGE_URL"] ?: fallback.targetFirmwareSourceZipImageUrl,
                targetFirmwareSourceZipImageSha256 = map["TARGET_FIRMWARE_SOURCE_ZIP_IMAGE_SHA256"] ?: fallback.targetFirmwareSourceZipImageSha256,
                targetFirmwareSourceZipImageSha256Unavailable = map["TARGET_FIRMWARE_SOURCE_ZIP_IMAGE_SHA256_UNAVAILABLE"]?.toBooleanStrictOrNull()
                    ?: fallback.targetFirmwareSourceZipImageSha256Unavailable,
                targetFsType = map["TARGET_FS_TYPE"] ?: fallback.targetFsType,
                targetHasSystemExt = map["TARGET_HAS_SYSTEM_EXT"]?.toBooleanStrictOrNull() ?: fallback.targetHasSystemExt,
                targetFlashablePartitions = map["TARGET_FLASHABLE_PARTITIONS"] ?: fallback.targetFlashablePartitions,
                targetFlashableBootPartitions = map["TARGET_FLASHABLE_BOOT_PARTITIONS"] ?: fallback.targetFlashableBootPartitions,
                targetFlashableBootSlots = map["TARGET_FLASHABLE_BOOT_SLOTS"] ?: fallback.targetFlashableBootSlots,
                targetFirmwareSourceDir = map["TARGET_FIRMWARE_SOURCE_DIR"] ?: fallback.targetFirmwareSourceDir,
                targetRecoverySystemMountPoint = map["TARGET_RECOVERY_SYSTEM_MOUNT_POINT"] ?: fallback.targetRecoverySystemMountPoint,
                targetRecoveryDynamicPartitionMetadataPolicy = map["TARGET_RECOVERY_DYNAMIC_PARTITION_METADATA_POLICY"]
                    ?: fallback.targetRecoveryDynamicPartitionMetadataPolicy,
                superPartitionSize = map["SUPER_PARTITION_SIZE"]?.toLongOrNull() ?: fallback.superPartitionSize,
                superMetadataSlots = map["SUPER_METADATA_SLOTS"]?.toIntOrNull() ?: fallback.superMetadataSlots,
                superVirtualAb = map["SUPER_VIRTUAL_AB"]?.toBooleanStrictOrNull() ?: fallback.superVirtualAb,
                targetDisableAvbSigning = map["TARGET_DISABLE_AVB_SIGNING"]?.toBooleanStrictOrNull() ?: fallback.targetDisableAvbSigning,
                superGroupName = map["SUPER_GROUP_NAME"] ?: fallback.superGroupName,
                superGroupSize = map["SUPER_GROUP_SIZE"]?.toLongOrNull() ?: fallback.superGroupSize,
                bootPartitionSize = map["BOOT_PARTITION_SIZE"]?.toLongOrNull() ?: fallback.bootPartitionSize,
                vendorBootPartitionSize = map["VENDOR_BOOT_PARTITION_SIZE"]?.toLongOrNull() ?: fallback.vendorBootPartitionSize,
                initBootPartitionSize = map["INIT_BOOT_PARTITION_SIZE"]?.toLongOrNull() ?: fallback.initBootPartitionSize,
                dtboPartitionSize = map["DTBO_PARTITION_SIZE"]?.toLongOrNull() ?: fallback.dtboPartitionSize,
                avbSigningKey = map["AVB_SIGNING_KEY"] ?: fallback.avbSigningKey,
                bootDevicePath = map["BOOT_DEVICE_PATH"] ?: fallback.bootDevicePath,
                targetBuildType = map["TARGET_BUILD_TYPE"] ?: fallback.targetBuildType,
                otaBaseUrl = map["OTA_BASE_URL"] ?: fallback.otaBaseUrl,
            )
        }
    }
}
