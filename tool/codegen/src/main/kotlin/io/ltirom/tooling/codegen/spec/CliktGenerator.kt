    private fun generateParentCli(spec: ToolSpecification, cliDir: File, toolPackage: String) {
        val toolName = spec.tool.capitalize().replace("-", "").replace(".", "")
        val className = "${toolName}CliCommand"
        val file = File(cliDir, "$className.kt")
        
        val content = buildString {
            appendLine("// This file is generated by tooling-codegen — do not edit by hand.")
            appendLine("// Regenerate via `./gradlew :tooling-codegen:generateToolAdapters`.")
            appendLine("package io.ltirom.tooling.adapters.$toolPackage.cli")
            appendLine()
            appendLine("import com.github.ajalt.clikt.core.CliktCommand")
            appendLine("import com.github.ajalt.clikt.core.Context")
            appendLine("import com.github.ajalt.clikt.core.subcommands")
            appendLine("import io.ltirom.tooling.core.ExecutionContext")
            appendLine("import io.ltirom.tooling.core.ToolRepository")
            appendLine("import io.ltirom.tooling.adapters.$toolPackage.*")
            appendLine()

            appendLine("public class $className(")
            appendLine("    private val repository: ToolRepository,")
            appendLine("    private val context: ExecutionContext")
            appendLine(") : CliktCommand(name = \"${spec.tool}\") {")
            appendLine()
            appendLine("    override fun help(context: Context): String = \"CLI entry point for ${spec.tool}\"")
            appendLine()
            appendLine("    init {")
            appendLine("        subcommands(")
            val subs = spec.commands.sortedBy { it.name }.map { cmd ->
                "            ${cmd.name.capitalize()}CliCommand(${cmd.name.capitalize()}UseCase(repository), context)"
            }
            appendLine(subs.joinToString(",\n"))
            appendLine("        )")
            appendLine("    }")
            appendLine()
            appendLine("    override fun run() {}")
            appendLine("}")
        }
        file.writeText(content)
    }

    private fun getCliktOptionDef(opt: OptionSpec, cmdName: String, toolPackage: String, allOptions: List<OptionSpec>): String {
        val names = getCliktOptionNames(opt, allOptions).joinToString { "\"$it\"" }
        val base = "option($names, help = \"${escape(opt.description)}\")"
        
        val transform = when (opt.type) {
            OptionType.BOOLEAN -> ".flag()"
            OptionType.STRING -> ""
            OptionType.INT -> ".int()"
            OptionType.PATH -> ".convert { File(it) }"
            OptionType.CHOICE -> {
                val enumName = cmdName.capitalize() + opt.name.capitalize() + "Type"
                ".convert { io.ltirom.tooling.adapters.$toolPackage.$enumName.valueOf(it.uppercase()) }"
            }
        }
        
        val required = if (opt.required && opt.type != OptionType.BOOLEAN) ".required()" else ""
        val multiple = if (opt.repeatable) ".multiple()" else ""
        
        return "$base$transform$required$multiple"
    }

    private fun getCliktOptionNames(opt: OptionSpec, allOptions: List<OptionSpec>): List<String> {
        val names = mutableListOf<String>()
        val longSpelling = if (opt.spelling.startsWith("--")) {
            opt.spelling
        } else {
            "--" + opt.name.replace(Regex("([a-z])([A-Z])"), "$1-$2").lowercase()
        }
        names.add(longSpelling)

        if (opt.spelling.startsWith("-") && !opt.spelling.startsWith("--")) {
            val hasCollision = allOptions.any { other ->
                other.name != opt.name && (other.spelling == opt.spelling || other.aliases.contains(opt.spelling))
            }
            if (!hasCollision) {
                names.add(opt.spelling)
            }
        }

        for (alias in opt.aliases) {
            val hasCollision = allOptions.any { other ->
                other.name != opt.name && (other.spelling == alias || other.aliases.contains(alias))
            }
            if (!hasCollision) {
                names.add(alias)
            }
        }
        return names.distinct()
    }

    private fun getCliktPropertyType(opt: OptionSpec, cmdName: String): String {
        val base = when (opt.type) {
            OptionType.BOOLEAN -> "Boolean"
            OptionType.STRING -> "String"
            OptionType.INT -> "Int"
            OptionType.PATH -> "File"
            OptionType.CHOICE -> cmdName.capitalize() + opt.name.capitalize() + "Type"
        }
        return if (opt.repeatable) {
            "List<$base>"
        } else if (opt.type == OptionType.BOOLEAN) {
            "Boolean"
        } else if (opt.required) {
            base
        } else {
            "$base?"
        }
    }

    private fun getCliktArgumentDef(arg: ArgumentSpec, cmdName: String, toolPackage: String): String {
        val base = "argument(name = \"${arg.name}\", help = \"${escape(arg.description)}\")"
        val transform = when (arg.type) {
            OptionType.BOOLEAN -> ""
            OptionType.STRING -> ""
            OptionType.INT -> ".int()"
            OptionType.PATH -> ".convert { File(it) }"
            OptionType.CHOICE -> {
                val enumName = cmdName.capitalize() + arg.name.capitalize() + "Type"
                ".convert { io.ltirom.tooling.adapters.$toolPackage.$enumName.valueOf(it.uppercase()) }"
            }
        }
        val optional = if (!arg.required && !arg.repeatable) ".optional()" else ""
        val multiple = if (arg.repeatable) ".multiple()" else ""
        return "$base$transform$optional$multiple"
    }

    private fun getCliktArgumentPropertyType(arg: ArgumentSpec, cmdName: String): String {
        val base = when (arg.type) {
            OptionType.BOOLEAN -> "Boolean"
            OptionType.STRING -> "String"
            OptionType.INT -> "Int"
            OptionType.PATH -> "File"
            OptionType.CHOICE -> cmdName.capitalize() + arg.name.capitalize() + "Type"
        }
        return if (arg.repeatable) {
            "List<$base>"
        } else if (arg.required) {
            base
        } else {
            "$base?"
        }
    }

    private fun escape(text: String): String {
        return text.replace("\\", "\\\\")
                   .replace("\"", "\\\"")
                   // Mordant's Markdown parser treats a literal dollar as syntax;
                   // use an entity in generated help while preserving source metadata.
                   .replace("$", "&#36;")
    }
}
private fun String.capitalize() = replaceFirstChar { if (it.isLowerCase()) it.titlecase() else it.toString() }
