package io.ltirom.tooling.codegen.spec

import java.io.File

object CliktGenerator {

    fun generate(spec: ToolSpecification, outputDir: File) {
        val toolPackage = spec.tool.lowercase().replace("-", "").replace(".", "")
        val cliDir = File(outputDir, "io/ltirom/tooling/adapters/$toolPackage/cli")
        cliDir.mkdirs()

        val hasSelf = spec.commands.size == 1 && spec.commands[0].subcommandPath == listOf("_self")

        if (hasSelf) {
            generateSingleCli(spec, spec.commands[0], cliDir, toolPackage)
        } else {
            // Generate subcommand Cli classes
            for (cmd in spec.commands.sortedBy { it.name }) {
                generateCommandCli(spec, cmd, cliDir, toolPackage)
            }
            // Generate parent Command class that bundles all subcommands
            generateParentCli(spec, cliDir, toolPackage)
        }
    }

    private fun generateSingleCli(
        spec: ToolSpecification,
        cmd: CommandSpec,
        cliDir: File,
        toolPackage: String
    ) {
        val toolName = spec.tool.capitalize().replace("-", "").replace(".", "")
        val className = "${toolName}CliCommand"
        val useCaseClass = "${cmd.name.capitalize()}UseCase"
        val file = File(cliDir, "$className.kt")
        val content = buildString {
            appendLine("// This file is generated by tooling-codegen — do not edit by hand.")
            appendLine("// Regenerate via `./gradlew :tooling-codegen:generateToolAdapters`.")
            appendLine("package io.ltirom.tooling.adapters.$toolPackage.cli")
            appendLine()
            appendLine("import com.github.ajalt.clikt.core.CliktCommand")
            appendLine("import com.github.ajalt.clikt.core.Context")
            appendLine("import com.github.ajalt.clikt.parameters.options.*")
            appendLine("import com.github.ajalt.clikt.parameters.arguments.*")
            appendLine("import com.github.ajalt.clikt.parameters.types.*")
            appendLine("import io.ltirom.tooling.core.ExecutionContext")
            appendLine("import io.ltirom.tooling.core.ToolRepository")
            appendLine("import io.ltirom.tooling.adapters.$toolPackage.*")
            appendLine("import java.io.File")
            appendLine()
            appendLine("public class $className(")
            appendLine("    private val useCase: $useCaseClass,")
            appendLine("    private val context: ExecutionContext")
            appendLine(") : CliktCommand(name = \"${spec.tool}\") {")
            appendLine()
            appendLine("    public constructor(repository: ToolRepository, context: ExecutionContext) : this($useCaseClass(repository), context)")
            appendLine()
            appendLine("    override fun help(context: Context): String = \"${escape(cmd.description)}\"")
            appendLine()

            // 1. Declare Option properties
            val distinctOptions = (spec.globalOptions + cmd.options).distinctBy { it.name }.sortedBy { it.name }
            for (opt in distinctOptions) {
                val cliktDef = getCliktOptionDef(opt, cmd.name, toolPackage, distinctOptions)
                appendLine("    public val ${opt.name}: ${getCliktPropertyType(opt, cmd.name)} by $cliktDef")
            }

            // 2. Declare Argument properties
            for (arg in cmd.arguments.sortedBy { it.name }) {
                val cliktDef = getCliktArgumentDef(arg, cmd.name, toolPackage)
                appendLine("    public val ${arg.name}: ${getCliktArgumentPropertyType(arg, cmd.name)} by $cliktDef")
            }

            appendLine()
            appendLine("    override fun run() {")
            appendLine("        kotlinx.coroutines.runBlocking {")
            appendLine("            useCase.execute(")
            val params = mutableListOf<String>()
            params.add("                context = context")
            for (opt in distinctOptions) {
                params.add("                ${opt.name} = ${opt.name}")
            }
            for (arg in cmd.arguments.sortedBy { it.name }) {
                params.add("                ${arg.name} = ${arg.name}")
            }
            appendLine(params.joinToString(",\n"))
            appendLine("            )")
            appendLine("        }")
            appendLine("    }")
            appendLine("}")
        }
        file.writeText(content)
    }

